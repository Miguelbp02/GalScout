-- Ojeo: tipo de observacion (partido/entrenamiento/otro), datos de partido
-- opcionales, y catalogo + registro de acciones tacticas del modo de ojeo
-- de partido en directo.
-- Ejecutar desde Supabase: SQL Editor > New query > Run.

-- Las observaciones existentes se quedan sin tipo (no sabemos cual era);
-- a partir de ahora el formulario obliga a elegir uno.
alter table public.observaciones_jugador
  add column if not exists tipo text,
  add column if not exists equipo_jugador_id uuid references public.equipos (id) on delete set null,
  add column if not exists equipo_rival_id uuid references public.equipos (id) on delete set null,
  add column if not exists competicion text,
  add column if not exists jornada text;

alter table public.observaciones_jugador
  drop constraint if exists observaciones_jugador_tipo_check;

alter table public.observaciones_jugador
  add constraint observaciones_jugador_tipo_check
  check (tipo is null or tipo in ('partido', 'entrenamiento', 'otro'));

-- Catalogo de etiquetas para las acciones del modo de ojeo de partido.
-- Igual que los criterios de scouting, distingue entre perfil de campo y portero.
create table if not exists public.etiquetas_accion (
  id bigint generated by default as identity primary key,
  nombre text not null,
  categoria text not null check (categoria in ('positiva', 'negativa', 'neutra')),
  perfil text not null default 'campo' check (perfil in ('campo', 'portero')),
  orden smallint not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  unique (perfil, nombre)
);

