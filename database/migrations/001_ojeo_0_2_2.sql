create table if not exists public.perfiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nombre text not null check (char_length(trim(nombre)) > 0),
  created_at timestamptz not null default now()
);

create or replace function public.crear_perfil_al_crear_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.perfiles (id, nombre)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'nombre', ''), split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists crear_perfil_nuevo_usuario on auth.users;

create trigger crear_perfil_nuevo_usuario
  after insert on auth.users
  for each row
  execute procedure public.crear_perfil_al_crear_usuario();

-- Crea perfiles para los usuarios que existían antes de instalar el trigger.
insert into public.perfiles (id, nombre)
select
  id,
  coalesce(nullif(raw_user_meta_data ->> 'nombre', ''), split_part(email, '@', 1))
from auth.users
on conflict (id) do nothing;

create table if not exists public.criterios_scouting (
