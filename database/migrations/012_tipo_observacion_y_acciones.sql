-- Cada accion cuelga directamente de la observacion a la que termina
-- perteneciendo: durante el partido en si viven solo en el cliente
-- (memoria + localStorage), y no se guardan aqui hasta que el ojeador
-- pulsa "Guardar informe" de ese jugador.
create table if not exists public.acciones_observacion (
  id uuid primary key default gen_random_uuid(),
  observacion_id uuid not null references public.observaciones_jugador (id) on delete cascade,
  etiqueta_id bigint not null references public.etiquetas_accion (id),
  minuto smallint not null check (minuto >= 0),
  parte smallint not null check (parte in (1, 2)),
  x numeric(5, 2) not null check (x between 0 and 100),
  y numeric(5, 2) not null check (y between 0 and 100),
  nota_libre text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists acciones_observacion_observacion_idx
  on public.acciones_observacion (observacion_id);

alter table public.etiquetas_accion enable row level security;
alter table public.acciones_observacion enable row level security;

