create table if not exists public.observaciones_jugador (
  id uuid primary key default gen_random_uuid(),
  jugador_id uuid not null references public.jugadores (id) on delete cascade,
  autor_id uuid not null default auth.uid() references auth.users (id) on delete restrict,
  fecha_observacion date not null default current_date,
  notas text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.valoraciones_observacion (
  observacion_id uuid not null references public.observaciones_jugador (id) on delete cascade,
  criterio_id bigint not null references public.criterios_scouting (id) on delete restrict,
  puntuacion smallint not null check (puntuacion between 0 and 20),
  created_at timestamptz not null default now(),
  primary key (observacion_id, criterio_id)
);

create table if not exists public.valoraciones_generales (
  id uuid primary key default gen_random_uuid(),
  jugador_id uuid not null references public.jugadores (id) on delete cascade,
  autor_id uuid not null default auth.uid() references auth.users (id) on delete restrict,
  fecha_valoracion date not null default current_date,
  puntuacion smallint not null check (puntuacion between 0 and 20),
  comentario text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists observaciones_jugador_jugador_fecha_idx
  on public.observaciones_jugador (jugador_id, fecha_observacion desc);

create index if not exists valoraciones_generales_jugador_fecha_idx
  on public.valoraciones_generales (jugador_id, fecha_valoracion desc);

